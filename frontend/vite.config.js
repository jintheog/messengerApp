import react from '@vitejs/plugin-react'
import { defineConfig } from 'vite'

// https://vite.dev/config/
export default defineConfig({
  plugins: [react()],
  // ── 프록시: CORS 를 우회하는 장치 ──────────────────────────
  // 프론트는 5173, 백엔드는 8080 에서 돌아간다.
  // 브라우저는 포트가 다르면 다른 사이트로 취급해서, 5173 화면이
  // 8080 을 직접 부르는 것을 막는다(CORS 정책).
  //
  // 해결책이 두 가지 있다.
  //   1. 백엔드에 "5173 은 허용" 설정 클래스를 추가한다
  //   2. Vite 가 대신 전달하게 한다  <- 이걸 택했다
  //
  // 아래 설정은 "/api 로 시작하는 요청은 Vite 개발 서버가 받아서
  // 8080 으로 대신 보내고 응답을 돌려준다"는 뜻이다.
  // 브라우저 입장에서는 계속 5173 만 부르는 것이라 CORS 가 발생하지 않는다.
  //
  // 이 방식을 고른 이유: 자바 코드가 한 줄도 늘지 않는다.
  // 그리고 실제 배포에서는 프론트 빌드 결과를 같은 서버에서 서비스하거나
  // Nginx 가 이 역할을 하므로, CORS 설정을 코드에 남기지 않는 편이 실전에 가깝다.

  server: {
    proxy: {
      '/api': 'http://localhost:8080',
    },
  },
})
