package org.example.backend.recipient;
/**
 * CSV로 들어온 휴대폰번호 문자열을 저장 가능한 형태(숫자만)로 바꾸고,
 * 규칙에 맞지 않으면 사유와 함께 예외를 던진다.
 *
 * 샘플 파일의 번호가 전부 012로 시작하는 가짜 번호이므로
 * 통신사 앞자리(010/011/016...)는 검사하지 않고 자릿수만 검사한다.
 */
public final class PhoneNormalizer {

    // 도구 모음이라 객체를 만들 이유가 없다. 객체가 기억할 상태가 없음 -> 인스턴스를 생성 할 이유가 없음.
    // new 를 막기 위해 생성자를 private 으로 둔다.
    // 생성자를 안 적으면 기본 생성자를 자동으로 만들어줘서 누군다 new 를 쓸 수 있게 된다.
    private PhoneNormalizer() { //담을 데이터가 없음.
    }


    // static: 객체 없이 클래스 이름으로 바로 호출
    public static String normalize(String raw) {

        // [1] 빈 값을 가장 먼저 걸러낸다.
        //     아래 모든 코드가 문자열을 만지므로 null 이면 가장 먼저 막음.
        if (raw == null || raw.isBlank()) {
            throw new InvalidRowException("휴대폰번호가 없습니다");
        }

        // [2] 앞뒤 공백 제거.
        //     " 012-6644-2288 " 처럼 공백이 붙어 오는 행이 있고,
        //     아래 startsWith("+82") 가 동작하려면 앞쪽 공백이 없어야 한다.
        String value = raw.trim();

        // [3] 국제표기를 국내표기로 바꾼다.
        //     substring(3) 은 앞 3글자("+82")를 잘라낸 나머지를 준다.
        //     "+82-12-3344-5566" -> "-12-3344-5566" -> 앞에 "0"을 붙여 "0-12-3344-5566"
        //     하이픈이 남지만 바로 다음 줄에서 사라진다.
        if (value.startsWith("+82")) {
            value = "0" + value.substring(3);
        }

        // [4] 하이픈과 공백을 모두 제거해 숫자열만 남긴다.
        //     정규식 [\s-] 의 의미:
        //       대괄호 [] = "이 안의 글자 중 아무거나 하나"
        //       \s      = 공백 문자 (스페이스, 탭, 개행)
        //       -       = 대괄호 안 맨 끝에 있으므로 '범위'가 아닌 하이픈 문자 그대로
        //     자바 문자열에서는 역슬래시를 \\ 로 써야 실제 \ 한 개가 된다.
        String digits = value.replaceAll("[\\s-]","");

        // [5] 남은 값이 전부 숫자인지 확인한다.
        //     \d = 숫자 한 글자(0~9), + = 앞의 것이 1개 이상
        //     matches() 는 문자열 '전체'가 패턴과 맞아야 true 이므로
        //     "\\d+" 는 "1글자 이상이고 전부 숫자"를 뜻한다.
        //     이 검사가 자릿수 검사보다 먼저여야 한다. "012-abc-1234" 같은 값은
        //     하이픈만 지워지면 10글자가 되어 자릿수 검사를 그냥 통과해버린다.
        if (!digits.matches("\\d+")) {
            throw new InvalidRowException("휴대폰번호에 숫자가 아닌 문자가 있습니다");
        }

        // [6] 엑셀이 앞자리 0을 날린 경우를 따로 잡는다. (샘플의 "1012345678")
        //     아래 [7]에 맡기면 "10자리라서 자릿수가 안 맞다"는 틀린 사유가 나온다.
        //     실제 문제는 자릿수가 아니라 앞자리 0이므로 사유를 구분한다.
        //     0을 붙여 자동 복원하지 않는 이유: 추측이 틀리면 엉뚱한 사람에게 문자가 간다.
        if (digits.length() == 10 && !digits.startsWith("0")) {
            throw new InvalidRowException("앞자리 0이 누락된 것으로 보입니다 (원본 확인 필요)");
        }

        // [7] 마지막으로 시작 숫자와 자릿수를 확인한다. 10~11자리, 0으로 시작만 통과.
        //     유선번호 "02-555-1234"(9자리), "012-88112-2233"(12자리),
        //     "012-7070"(7자리)이 모두 여기서 걸린다.
        if (!digits.startsWith("0") || digits.length() < 10 || digits.length() > 11) {
            throw new InvalidRowException(
                    "휴대폰번호 자릿수가 맞지 않습니다 (" + digits.length() + "자리)");
        }
        return digits;
    }

}
