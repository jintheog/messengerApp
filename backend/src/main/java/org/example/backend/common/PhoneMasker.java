package org.example.backend.common;

/**
 * 저장된 휴대폰번호(숫자만)를 화면에 보여줄 형태로 바꾼다.
 *   01012345678 -> 010-****-5678
 *
 * ── 왜 common 패키지인가 ──
 * 수신자 목록에도, 발송 이력에도, 발송 로그에도 번호가 나간다.
 * recipient 패키지에 두면 message 패키지가 recipient 를 import 해야 하는데,
 * 그건 "메시지가 수신자에 의존한다"는 잘못된 신호를 준다.
 * 마스킹은 특정 도메인의 규칙이 아니라 앱 전체의 표시 규칙이므로 common 에 둔다.
 *
 * ── 왜 저장은 평문이고 표시할 때만 가리는가 ──
 * 1. 발송에는 원본 번호가 필요하다. 가려서 저장하면 문자를 보낼 수 없다.
 * 2. 중복 판정을 번호로 하는데, 가려서 저장하면 010-****-5678 끼리
 *    구별이 안 돼서 서로 다른 사람이 같은 번호로 취급된다.
 * 그래서 DB에는 평문으로 두고, 밖으로 나가는 순간(DTO로 변환할 때) 가린다.
 *
 * 암호화하지 않은 것은 과제 범위를 넘어선다는 판단이다. 실무라면
 * 컬럼 암호화나 별도 보관소를 검토해야 하고, 이건 README에 적었다.
 */
public final class PhoneMasker {

    // 도구 모음이라 객체를 만들 이유가 없다. 기억할 상태가 없다.
    // 생성자를 아예 안 적으면 자바가 기본 생성자를 만들어줘서 누군가 new 를 할 수 있다.
    // private 으로 막아 "이 클래스는 인스턴스를 만드는 게 아니다"를 문법으로 표현한다.
    private PhoneMasker() {
    }

    /**
     * @param digits 숫자만 들어 있는 번호. PhoneNormalizer 를 통과한 값이다.
     * @return 가운데를 가린 문자열
     */
    public static String mask(String digits) {

        // ── 방어 코드를 둔 이유 ──
        // 저장된 번호는 파서를 통과했으니 10~11자리가 보장된다.
        // 그런데 이 메서드는 발송 이력의 스냅샷 번호에도 쓰이고, 그 데이터는
        // 몇 달 전에 다른 규칙으로 저장됐을 수도 있다. 규칙이 바뀌면
        // 예상 밖의 값이 들어올 수 있다.
        //
        // 그때 예외를 던지면 목록 조회 화면 전체가 500 에러로 죽는다.
        // 번호 하나가 이상해서 화면이 안 열리는 건 과한 대가다.
        // 대신 전부 가려서 돌려준다. 판단이 안 서면 더 많이 가리는 쪽을 택한다.
        if (digits == null || digits.length() < 7) {
            return "****";
        }

        // ── substring 문법 ──
        // substring(0, 3)  : 0번째부터 3번째 '앞'까지. 즉 앞 3글자.
        //                    끝 번호는 포함하지 않는다는 게 자바의 규칙이다.
        // substring(n)     : n번째부터 끝까지
        // length() - 4     : 뒤에서 4번째 위치. 그래서 마지막 4글자를 뜻한다.
        //
        // 앞 3자리와 뒤 4자리를 남기는 이유:
        // 요구사항 예시가 010-****-5678 이다. 앞 3자리는 통신사 식별에,
        // 뒤 4자리는 담당자가 "내가 아는 그 사람인지" 확인하는 데 쓰인다.
        // 가운데를 가리면 번호를 완성할 수 없어 유출되어도 발신이 불가능하다.
        String head = digits.substring(0, 3);
        String tail = digits.substring(digits.length() - 4);

        // 가운데를 자릿수에 맞춰 별표를 세지 않고 항상 4개로 고정한 이유:
        // 별표 개수가 자릿수를 알려주면 정보가 조금이라도 새어나간다.
        // 어차피 가리는 것이 목적이므로 개수를 노출할 이유가 없다.
        // 10자리든 11자리든 같은 모양으로 나와서 화면 정렬도 깔끔해진다.
        return head + "-****-" + tail;
    }
}